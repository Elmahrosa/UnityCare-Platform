--   diagnosis: String (required),
--   treatment: String (required),
--   medications: [{ name, dosage, frequency, duration }],
--   notes: String,
--   attachments: [{ filename, url, uploadedAt }],
--   integrityHash: String,
--   deletedAt: Date (nullable, for GDPR soft-delete),
--   createdAt: Date,
--   updatedAt: Date
-- }
